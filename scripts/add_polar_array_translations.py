def add_translations_to_ts():
    files = [f for f in os.listdir(i18n_dir) if f.endswith(".ts")]
    for filename in files:
        lang = filename.replace("fillet_", "").replace(".ts", "")
        ts_path = os.path.join(i18n_dir, filename)

        tree = ET.parse(ts_path)
        root = tree.getroot()

        # Find or create context 'FilletPlugin'
        plugin_context = None
        for ctx in root.findall("context"):
            name = ctx.find("name")
            if name is not None and name.text == "FilletPlugin":
                plugin_context = ctx
                break

        if plugin_context is None:
            plugin_context = ET.SubElement(root, "context")
            name_el = ET.SubElement(plugin_context, "name")
            name_el.text = "FilletPlugin"

        # Existing sources in this context
        existing_sources = set()
        for msg in plugin_context.findall("message"):
            src = msg.find("source")
            if src is not None and src.text:
                existing_sources.add(src.text)

        added = 0
        for src_text, trans_dict in POLAR_ARRAY_STRINGS.items():
            if src_text in existing_sources:
                continue

            trans_text = trans_dict.get(lang, trans_dict.get('en', src_text))
            msg_el = ET.SubElement(plugin_context, "message")
            s_el = ET.SubElement(msg_el, "source")
            s_el.text = src_text
            t_el = ET.SubElement(msg_el, "translation")
            t_el.text = trans_text
            added += 1

        if added > 0:
            xml_str = ET.tostring(root, encoding="utf-8")
            reparsed = minidom.parseString(xml_str)
            with open(ts_path, "wb") as f:
                f.write(reparsed.toprettyxml(indent="    ", encoding="utf-8"))
            print(f"Updated {filename}: +{added} strings")


def compile_all_qm():
    sys.path.insert(0, os.path.dirname(__file__))
    from compile_translations import build_qm_data
    files = [f for f in os.listdir(i18n_dir) if f.endswith(".ts")]
    for f in files:
        lang = f.replace("fillet_", "").replace(".ts", "")
        ts_p = os.path.join(i18n_dir, f)
        qm_p = os.path.join(i18n_dir, f.replace(".ts", ".qm"))
        
        tree = ET.parse(ts_p)
        root = tree.getroot()
        trans_tuples = []
        for ctx in root.findall("context"):
            name_el = ctx.find("name")
            ctx_name = name_el.text if name_el is not None else ""
            for msg in ctx.findall("message"):
                src_el = msg.find("source")
                tr_el = msg.find("translation")
                src = src_el.text if src_el is not None and src_el.text else ""
                tr = tr_el.text if tr_el is not None and tr_el.text else src
                if src:
                    trans_tuples.append((ctx_name, src, tr, ""))
        qm_bytes = build_qm_data(trans_tuples, lang)
        with open(qm_p, "wb") as qm_file:
            qm_file.write(qm_bytes)
    print(f"Compiled {len(files)} QM files.")


if __name__ == "__main__":
    add_translations_to_ts()
    compile_all_qm()


