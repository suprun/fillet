def add_translations_to_ts(ts_path, lang_code):
    """Adds missing strings to a single .ts file."""
    tree = ET.parse(ts_path)
    root = tree.getroot()

    context = root.find("context")
    if context is None:
        context = ET.SubElement(root, "context")
        name = ET.SubElement(context, "name")
        name.text = "FilletPlugin"

    existing_sources = set()
    for msg in context.findall("message"):
        source = msg.find("source")
        if source is not None and source.text:
            existing_sources.add(source.text)

    added_count = 0
    for src_text, trans_dict in ORTHO_ANGLES_STRINGS.items():
        if src_text not in existing_sources:
            msg = ET.SubElement(context, "message")
            s = ET.SubElement(msg, "source")
            s.text = src_text
            t = ET.SubElement(msg, "translation")
            trans_text = trans_dict.get(lang_code, trans_dict.get("en", src_text))
            t.text = trans_text
            added_count += 1

    if added_count > 0:
        # Write pretty XML
        xml_str = ET.tostring(root, encoding="utf-8")
        parsed = minidom.parseString(xml_str)
        # Remove extra blank lines minidom adds
        clean_xml = "\n".join([line for line in parsed.toprettyxml(indent="    ").split("\n") if line.strip()])
        with open(ts_path, "w", encoding="utf-8") as f:
            f.write(clean_xml + "\n")

    return added_count


def main():
    if not os.path.exists(i18n_dir):
        print(f"i18n dir not found: {i18n_dir}")
        return 1

    ts_files = [f for f in os.listdir(i18n_dir) if f.endswith(".ts")]
    print(f"Found {len(ts_files)} .ts files in {i18n_dir}")

    total_added = 0
    for ts_file in ts_files:
        lang_code = ts_file.replace("fillet_", "").replace(".ts", "")
        ts_path = os.path.join(i18n_dir, ts_file)
        added = add_translations_to_ts(ts_path, lang_code)
        if added > 0:
            print(f" - {ts_file}: added {added} translations")
            total_added += added

    print(f"Total translations added: {total_added}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
