def elf_hash(source_text: str, comment: str = "") -> int:
    h = 0
    for b in source_text.encode('utf-8'):
        h = ((h << 4) + b) & 0xFFFFFFFF
        g = h & 0xf0000000
        if g != 0:
            h ^= (g >> 24)
        h &= ~g
        h &= 0xFFFFFFFF
    
    if comment:
        for b in comment.encode('utf-8'):
            h = ((h << 4) + b) & 0xFFFFFFFF
            g = h & 0xf0000000
            if g != 0:
                h ^= (g >> 24)
            h &= ~g
            h &= 0xFFFFFFFF
            
    if h == 0:
        h = 1
    return h

def build_qm_data(translations: list, language: str = "") -> bytes:
    """
    translations: list of tuples (context, source_text, translation_text, comment)
    """
    MAGIC = bytes([
        0x3c, 0xb8, 0x64, 0x18, 0xca, 0xef, 0x9c, 0x95,
        0xcd, 0x21, 0x1c, 0xbf, 0x60, 0xa1, 0xbd, 0xdd
    ])
    
    TAG_END = 1
    TAG_TRANSLATION = 3
    TAG_SOURCETEXT = 6
    TAG_CONTEXT = 7
    TAG_COMMENT = 8
    
    TAG_HASHES_SECTION = 0x42
    TAG_MESSAGES_SECTION = 0x69
    TAG_LANGUAGE_SECTION = 0xa7
    
    messages_block = bytearray()
    hash_entries = []
    
    for context, source, trans, comment in translations:
        offset = len(messages_block)
        h = elf_hash(source, comment)
        hash_entries.append((h, offset))
        
        # Tag_SourceText
        src_bytes = source.encode('utf-8')
        messages_block.append(TAG_SOURCETEXT)
        messages_block.extend(struct.pack('>I', len(src_bytes)))
        messages_block.extend(src_bytes)
        
        # Tag_Context
        if context:
            ctx_bytes = context.encode('utf-8')
            messages_block.append(TAG_CONTEXT)
            messages_block.extend(struct.pack('>I', len(ctx_bytes)))
            messages_block.extend(ctx_bytes)
            
        # Tag_Comment
        if comment:
            cmt_bytes = comment.encode('utf-8')
            messages_block.append(TAG_COMMENT)
            messages_block.extend(struct.pack('>I', len(cmt_bytes)))
            messages_block.extend(cmt_bytes)
            
        # Tag_Translation (UTF-16BE)
        trans_utf16 = trans.encode('utf-16-be')
        messages_block.append(TAG_TRANSLATION)
        messages_block.extend(struct.pack('>I', len(trans_utf16)))
        messages_block.extend(trans_utf16)
        
        # Tag_End
        messages_block.append(TAG_END)
        
    hash_entries.sort(key=lambda x: x[0])
    
    hashes_block = bytearray()
    for h, off in hash_entries:
        hashes_block.extend(struct.pack('>II', h, off))
        
    result = bytearray(MAGIC)
    
    if language:
        lang_bytes = language.encode('utf-8')
        result.append(TAG_LANGUAGE_SECTION)
        result.extend(struct.pack('>I', len(lang_bytes)))
        result.extend(lang_bytes)
        
    result.append(TAG_HASHES_SECTION)
    result.extend(struct.pack('>I', len(hashes_block)))
    result.extend(hashes_block)
    
    result.append(TAG_MESSAGES_SECTION)
    result.extend(struct.pack('>I', len(messages_block)))
    result.extend(messages_block)
    
    return bytes(result)

def generate_ts_file(lang: str, output_path: str):
    """Generate Qt XML .ts file."""
    root = ET.Element("TS", version="2.1", language=lang)
    
    for context_name, messages in STRINGS.items():
        ctx_elem = ET.SubElement(root, "context")
        name_elem = ET.SubElement(ctx_elem, "name")
        name_elem.text = context_name
        
        for source_text, translations in messages.items():
            msg_elem = ET.SubElement(ctx_elem, "message")
            src_elem = ET.SubElement(msg_elem, "source")
            src_elem.text = source_text
            
            trans_elem = ET.SubElement(msg_elem, "translation")
            trans_text = translations.get(lang, translations.get("en", source_text))
            trans_elem.text = trans_text
            
    xml_str = ET.tostring(root, encoding="utf-8")
    parsed = minidom.parseString(xml_str)
    pretty_xml = parsed.toprettyxml(indent="    ", encoding="utf-8")
    
    with open(output_path, "wb") as f:
        f.write(pretty_xml)

def compile_all():
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    i18n_dir = os.path.join(base_dir, "i18n")
    os.makedirs(i18n_dir, exist_ok=True)
    
    print(f"Compiling translations to: {i18n_dir}")
    
    for lang in LANGUAGES:
        ts_path = os.path.join(i18n_dir, f"fillet_{lang}.ts")
        qm_path = os.path.join(i18n_dir, f"fillet_{lang}.qm")
        
        # 1. Generate .ts
        generate_ts_file(lang, ts_path)
        
        # 2. Build list of translation tuples for .qm
        trans_tuples = []
        for context_name, messages in STRINGS.items():
            for source_text, translations in messages.items():
                trans_text = translations.get(lang, translations.get("en", source_text))
                trans_tuples.append((context_name, source_text, trans_text, ""))
                
        # 3. Generate binary .qm
        qm_bytes = build_qm_data(trans_tuples, lang)
        with open(qm_path, "wb") as f:
            f.write(qm_bytes)
            
        print(f"  [OK] fillet_{lang}.ts ({os.path.getsize(ts_path)} B) -> fillet_{lang}.qm ({len(qm_bytes)} B)")
        
    print("All translations generated and compiled successfully!")

if __name__ == "__main__":
    compile_all()
